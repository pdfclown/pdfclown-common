/*
  Copies the aggregate `NOTICE` file generated by `maven-shade-plugin` to ancillary artifacts
  (namely, sources and javadoc jars).
 */

import java.nio.file.FileSystems
import java.nio.file.Files
import java.nio.file.Path
import java.util.zip.ZipFile
import org.codehaus.plexus.util.xml.Xpp3Dom

log.info("")
log.info("Merged NOTICE packing ".padRight(72, '-'))

final String JAR_ENTRY__NOTICE = 'META-INF/NOTICE.txt'

// 1. Skip whenever this module is not shaded!
def shadePlugin = project.buildPlugins.find {
  it.key == 'org.apache.maven.plugins:maven-shade-plugin'
}
def configured = shadePlugin?.executions?.any { it.goals.contains('shade') }
if (!shadePlugin) {
  log.info('Not a shaded project -- execution SKIPPED')
  return
} else if (!shadePlugin.executions?.any { it.goals.contains('shade') }) {
  log.warn('Not a shaded project (`maven-shade-plugin` without `shade` goal) -- execution ' +
      'SKIPPED')
  return
}

// 2. Find the shaded jar file!
def confValue = { String name, String defaultValue ->
  def doms = [shadePlugin.configuration] /* Plugin-level configuration */ +
      shadePlugin.executions.collect { it.configuration } /* Execution-level configurations */
  for (d in doms) {
    def v = (d as Xpp3Dom)?.getChild(name)?.value?.trim()
    if (v)
      return v
  }
  return defaultValue
}
String shadedClassifier = confValue('shadedClassifierName', 'shaded')
log.debug("shadedClassifier: ${shadedClassifier}")

def attachedArtifact = project.attachedArtifacts.find { it.classifier == shadedClassifier }
log.debug("attachedArtifact: ${attachedArtifact}")

File shadedJarFile = null
// Attached jar?
if (attachedArtifact?.file?.exists()) {
  shadedJarFile = attachedArtifact.file
}
// Main jar (replaced the original one, renamed as `original-<jarname>.jar`).
else {
  def mainJar = project.artifact.file
  def original = mainJar ? new File(mainJar.parentFile, "original-${mainJar.name}") : null
  if (original?.exists()) {
    shadedJarFile = mainJar
  }
}
if (!shadedJarFile)
  throw new IllegalStateException("Shaded jar NOT FOUND")

// 3. Extract the merged NOTICE!
byte[] notice
new ZipFile(shadedJarFile).withCloseable { zip ->
  def entry = zip.getEntry(JAR_ENTRY__NOTICE)
  if (entry == null) {
    log.warn("${shadedJarFile.name} contains no ${JAR_ENTRY__NOTICE}, skipping")
    return
  }
  notice = zip.getInputStream(entry).withCloseable { it.bytes }
}
if (notice == null)
  throw new IllegalStateException("`${JAR_ENTRY__NOTICE}` in ${shadedJarFile} NOT FOUND")

// 4. Insert the merged NOTICE into the ancillary jars!
['sources', 'javadoc'].each { String classifier ->
  File targetFile = project.attachedArtifacts.find { it.classifier == classifier }?.file
  if (targetFile == null || !targetFile.isFile()) {
    log.info("* ${classifier}: no jar attached -- SKIPPED")
    return
  }

  /*
    NOTE: In case of existing entry, it is overwritten.
  */
  FileSystems.newFileSystem(URI.create('jar:' + targetFile.toURI()), [:]).withCloseable {
    Path dest = it.getPath(JAR_ENTRY__NOTICE)
    Files.createDirectories(dest.parent)
    Files.write(dest, notice)
  }
  log.info("* ${classifier}: merged `${JAR_ENTRY__NOTICE}` from shaded `${shadedJarFile}` " +
      "ADDED to `${targetFile}`")
}
